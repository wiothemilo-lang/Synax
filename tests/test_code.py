import ast

import pytest

from synax.data.code import (
    is_permissive,
    is_quality_python,
    normalize_code,
    prepare_python_corpus,
)

GOOD_CODE = '''\
import math


def area(radius: float) -> float:
    """Return the area of a circle."""
    if radius < 0:
        raise ValueError("radius must be non-negative")
    return math.pi * radius**2


def main() -> None:
    for value in range(5):
        print(value, area(value))


if __name__ == "__main__":
    main()
'''


def test_normalize_code_preserves_indentation() -> None:
    source = "def f():\r\n\tif True:\r\n\t\treturn 1\r\n"
    normalized = normalize_code(source)
    assert normalized == "def f():\n\tif True:\n\t\treturn 1\n"


def test_quality_accepts_valid_python() -> None:
    assert is_quality_python(GOOD_CODE, min_lines=5)


def test_quality_rejects_syntax_error() -> None:
    broken = "def f(:\n    return 1\n" * 20
    assert not is_quality_python(broken, min_lines=5)


def test_quality_rejects_autogenerated() -> None:
    generated = "# This file is auto-generated. Do not edit.\n" + GOOD_CODE
    assert not is_quality_python(generated, min_lines=5)


def test_quality_rejects_long_lines() -> None:
    long_line = "x = '" + "a" * 600 + "'\n"
    assert not is_quality_python(long_line * 20, min_lines=5)


def test_permissive_license_filter() -> None:
    allow = {"mit", "apache-2.0"}
    assert is_permissive("MIT", allow, include_unknown=False)
    assert not is_permissive("gpl-3.0", allow, include_unknown=False)
    assert not is_permissive("unknown", allow, include_unknown=False)
    assert is_permissive("unknown", allow, include_unknown=True)


def test_prepare_corpus_filters_and_writes(tmp_path) -> None:
    records = [
        {"content": GOOD_CODE, "license": "mit", "repo_name": "a/b", "path": "a.py"},
        {"content": GOOD_CODE, "license": "gpl-3.0", "repo_name": "c/d", "path": "b.py"},
        {"content": "def broken(:\n    pass\n" * 20, "license": "mit", "repo_name": "e/f"},
        {"content": GOOD_CODE, "license": "apache-2.0", "repo_name": "g/h", "path": "c.py"},
    ]
    output = tmp_path / "python.jsonl"
    stats = prepare_python_corpus(records, output, min_lines=5, progress_every=0)

    assert stats["seen"] == 4
    assert stats["license_skipped"] == 1
    assert stats["bad_code"] == 1
    assert stats["duplicate"] == 1
    assert stats["kept"] == 1

    rows = output.read_text(encoding="utf-8").splitlines()
    assert len(rows) == 1
    assert "def area" in rows[0]


def test_prepare_corpus_max_bytes(tmp_path) -> None:
    records = [
        {"content": GOOD_CODE + f"\n# variant {i}\n", "license": "mit"} for i in range(10)
    ]
    output = tmp_path / "python.jsonl"
    stats = prepare_python_corpus(
        records,
        output,
        min_lines=5,
        max_bytes=len(GOOD_CODE),
        progress_every=0,
    )
    assert stats["kept"] == 1
    assert stats["bytes"] >= len(GOOD_CODE)


def test_ast_parse_matches_quality() -> None:
    ast.parse(GOOD_CODE)
    with pytest.raises(SyntaxError):
        ast.parse("def f(:\n")
