"""Prepare a permissively licensed Python corpus from a Hugging Face dataset."""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import re
import warnings
from collections.abc import Iterable, Iterator
from pathlib import Path
from typing import Any

from synax.data.pipeline import MinHashDeduper

PERMISSIVE_LICENSES = {
    "0bsd",
    "apache-2.0",
    "bsd-2-clause",
    "bsd-3-clause",
    "cc0-1.0",
    "isc",
    "mit",
    "unlicense",
}

_AUTOGENERATED_RE = re.compile(
    r"(auto-?generated|generated by|do not edit|this file is generated|@generated)",
    re.IGNORECASE,
)
_NULL_RE = re.compile(r"\x00")


def normalize_code(text: str) -> str:
    """Normalize line endings and trailing whitespace without touching indentation."""

    text = text.replace("\r\n", "\n").replace("\r", "\n")
    text = _NULL_RE.sub("", text)
    lines = [line.rstrip() for line in text.split("\n")]
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    return "\n".join(lines) + ("\n" if lines else "")


def is_quality_python(
    text: str,
    *,
    min_lines: int = 10,
    max_lines: int = 5000,
    max_line_length: int = 500,
    min_alnum_ratio: float = 0.25,
) -> bool:
    lines = text.splitlines()
    if not (min_lines <= len(lines) <= max_lines):
        return False
    if not text.strip():
        return False
    if max(len(line) for line in lines) > max_line_length:
        return False

    alnum = sum(ch.isalnum() for ch in text)
    if alnum / len(text) < min_alnum_ratio:
        return False

    if _AUTOGENERATED_RE.search(text[:2000]):
        return False

    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", SyntaxWarning)
            ast.parse(text)
    except (SyntaxError, ValueError, MemoryError, RecursionError):
        return False
    return True


def is_permissive(license_name: str | None, allow: set[str], include_unknown: bool) -> bool:
    if not license_name:
        return include_unknown
    normalized = license_name.strip().lower()
    if normalized in allow:
        return True
    return include_unknown and normalized in {"unknown", "other", "no-license", "none"}


def iter_dataset_records(
    dataset: str,
    split: str = "train",
    streaming: bool = True,
) -> Iterator[dict[str, Any]]:
    from datasets import load_dataset

    data = load_dataset(dataset, split=split, streaming=streaming)
    yield from data


def prepare_python_corpus(
    records: Iterable[dict[str, Any]],
    output: str | Path,
    *,
    licenses: set[str] | None = None,
    include_unknown_license: bool = False,
    min_lines: int = 10,
    max_lines: int = 5000,
    max_line_length: int = 500,
    min_alnum_ratio: float = 0.25,
    dedupe: str = "exact",
    max_docs: int | None = None,
    max_bytes: int | None = None,
    max_seen: int | None = None,
    progress_every: int = 10_000,
) -> dict[str, int]:
    allow = licenses or set(PERMISSIVE_LICENSES)
    output_path = Path(output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = output_path.with_name(output_path.name + ".tmp")
    tmp_path.unlink(missing_ok=True)

    seen_hashes: set[str] = set()
    minhash = MinHashDeduper(threshold=0.9) if dedupe == "minhash" else None

    stats = {
        "seen": 0,
        "license_skipped": 0,
        "bad_code": 0,
        "duplicate": 0,
        "kept": 0,
        "bytes": 0,
    }

    with tmp_path.open("w", encoding="utf-8") as handle:
        for record in records:
            stats["seen"] += 1
            if max_seen is not None and stats["seen"] > max_seen:
                break

            license_name = record.get("license")
            if not is_permissive(license_name, allow, include_unknown_license):
                stats["license_skipped"] += 1
                continue

            content = record.get("content") or ""
            code = normalize_code(content)
            if not is_quality_python(
                code,
                min_lines=min_lines,
                max_lines=max_lines,
                max_line_length=max_line_length,
                min_alnum_ratio=min_alnum_ratio,
            ):
                stats["bad_code"] += 1
                continue

            if minhash is not None:
                if not minhash.add(code):
                    stats["duplicate"] += 1
                    continue
            elif dedupe == "exact":
                digest = hashlib.sha256(code.encode("utf-8")).hexdigest()
                if digest in seen_hashes:
                    stats["duplicate"] += 1
                    continue
                seen_hashes.add(digest)
            elif dedupe != "none":
                raise ValueError(f"unknown dedupe mode: {dedupe}")

            row = {
                "text": code,
                "repo": record.get("repo_name", ""),
                "path": record.get("path", ""),
                "license": license_name or "",
            }
            line = json.dumps(row, ensure_ascii=False) + "\n"
            handle.write(line)
            stats["kept"] += 1
            stats["bytes"] += len(line.encode("utf-8"))

            if progress_every > 0 and stats["seen"] % progress_every == 0:
                print(json.dumps(stats), flush=True)
            if max_docs is not None and stats["kept"] >= max_docs:
                break
            if max_bytes is not None and stats["bytes"] >= max_bytes:
                break

    tmp_path.replace(output_path)
    return stats


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Build a permissively licensed Python corpus")
    parser.add_argument("--dataset", default="codeparrot/codeparrot-clean")
    parser.add_argument("--split", default="train")
    parser.add_argument("--output", required=True, help="output .jsonl")
    parser.add_argument(
        "--licenses",
        default=",".join(sorted(PERMISSIVE_LICENSES)),
        help="comma-separated SPDX license allowlist",
    )
    parser.add_argument("--include-unknown-license", action="store_true")
    parser.add_argument("--min-lines", type=int, default=10)
    parser.add_argument("--max-lines", type=int, default=5000)
    parser.add_argument("--max-line-length", type=int, default=500)
    parser.add_argument("--min-alnum-ratio", type=float, default=0.25)
    parser.add_argument("--dedupe", choices=["none", "exact", "minhash"], default="exact")
    parser.add_argument("--max-docs", type=int, default=None)
    parser.add_argument("--max-bytes", type=int, default=None)
    parser.add_argument("--max-seen", type=int, default=None)
    parser.add_argument("--progress-every", type=int, default=10_000)
    args = parser.parse_args(argv)

    licenses = {item.strip().lower() for item in args.licenses.split(",") if item.strip()}
    stats = prepare_python_corpus(
        iter_dataset_records(args.dataset, args.split),
        args.output,
        licenses=licenses,
        include_unknown_license=args.include_unknown_license,
        min_lines=args.min_lines,
        max_lines=args.max_lines,
        max_line_length=args.max_line_length,
        min_alnum_ratio=args.min_alnum_ratio,
        dedupe=args.dedupe,
        max_docs=args.max_docs,
        max_bytes=args.max_bytes,
        max_seen=args.max_seen,
        progress_every=args.progress_every,
    )
    print(json.dumps(stats, ensure_ascii=False))


if __name__ == "__main__":
    main()
